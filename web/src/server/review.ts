function plannedClips(job: { production_path: string; video_provider: string }): Json[] {
  const p = readJsonFile<Json>(repoPath(job.production_path));
  return job.video_provider === "seedance" ? p.seedance_prompts : p.flow_prompts;
}

/**
 * Store a manually rendered MP4 for one clip. The file is streamed to
 * outputs/<job>/renders/<clip>_aNN.mp4 with a size limit and a content check.
 */
export async function uploadRender(jobId: string, clipId: string, body: ReadableStream<Uint8Array> | null, meta: {
  filename: string; credits: number | null; est_cost: number | null; currency: string | null; is_test_media: boolean;
}, actor: Actor): Promise<Render> {
  const job = getJob(jobId);
  if (!["AWAITING_RENDER", "RENDER_UPLOADED", "QC_PENDING"].includes(job.state)) throw conflict(`renders can be uploaded while awaiting render or in review; the job is ${job.state}`);
  if (!/^C\d{2,3}$/.test(clipId)) throw badRequest("bad clip id");
  const clip = plannedClips(job).find((c) => c.clip_id === clipId);
  if (!clip) throw badRequest(`clip ${clipId} is not planned for this job`);
  safeFileName(meta.filename || "render.mp4", "video"); // extension check
  const attempt = nextAttempt(jobId, clipId);
  const rel = `outputs/${jobId}/renders/${clipId}_a${String(attempt).padStart(2, "0")}.mp4`;
  const { bytes, sha256 } = await saveUpload(body, repoPath(rel), "video");
  let info: Json;
  try {
    info = await probe(rel);
  } catch (e) {
    fs.rmSync(repoPath(rel), { force: true });
    throw new AppError(422, "not_a_video", `FFmpeg could not read the upload: ${e instanceof Error ? e.message : e}`);
  }
  const render = insertRender({
    job_id: jobId, clip_id: clipId, attempt, path: rel, provider: job.video_provider, original_name: path.basename(meta.filename).slice(0, 200),
    bytes, sha256, credits: meta.credits, est_cost: meta.est_cost, currency: meta.currency, is_test_media: meta.is_test_media || job.is_test,
  });
  updateRender(jobId, render.id, { probe: info });
  if (meta.credits != null) {
    recordUsage({ job_id: jobId, provider: job.video_provider, kind: "actual", units: meta.credits, unit_type: "credits", amount: null, currency: null, note: `${clipId} attempt ${attempt}: credits reported by the person who rendered it` });
    const price = env().flowCreditCost;
    if (meta.est_cost == null && price.amount > 0) {
      recordUsage({ job_id: jobId, provider: job.video_provider, kind: "estimate", units: meta.credits, unit_type: "credits", amount: +(meta.credits * price.amount).toFixed(4), currency: price.currency, note: "estimate: credits × ACS_FLOW_COST_PER_CREDIT" });
    }
  }
  if (meta.est_cost != null) recordUsage({ job_id: jobId, provider: job.video_provider, kind: "estimate", units: null, unit_type: null, amount: meta.est_cost, currency: meta.currency ?? "USD", note: `${clipId} attempt ${attempt}: cost entered by the user (estimate)` });
  transition(jobId, "RENDER_UPLOADED", actor, `${clipId} take ${attempt} uploaded (${(bytes / 1024 / 1024).toFixed(1)} MB${meta.is_test_media ? ", TEST MEDIA — not generated by a provider" : ""})`);
  await syncProductionStatus(jobId);
  return getRender(jobId, render.id);
}

/** Attach = technical checks + contact sheet + first frame. When every clip has a take, review opens. */
export async function attachRenders(jobId: string, renderIds: number[] | null, actor: Actor) {
  const job = getJob(jobId);
  if (!["RENDER_UPLOADED", "QC_PENDING"].includes(job.state)) return { attached: [], state: job.state, message: `nothing to attach in ${job.state}` };
  const pending = listRenders(jobId).filter((r) => r.status === "uploaded" && (!renderIds || renderIds.includes(r.id)));
  const p = readJsonFile<Json>(repoPath(job.production_path));
  const attached: Json[] = [];
  for (const r of pending) {
    const base = r.path.replace(/\.mp4$/, "");
    const sheet = `${base}_contact.jpg`;
    const first = `${base}_first.png`;
    await service(["contact-sheet", r.path, "--out", sheet, "--every", "0.5"], 300_000);
    await service(["frame", r.path, "--out", first, "--at", "0"]);
    const clip = plannedClips(job).find((c) => c.clip_id === r.clip_id);
    const info = (r.probe ?? (await probe(r.path))) as Json;
    const planned = clip ? clip.end_seconds - clip.start_seconds : null;
    const checks: string[] = [];
    if (planned != null && Math.abs(info.duration_seconds - planned) > 0.5) checks.push(`length ${info.duration_seconds}s vs planned ${planned}s`);
    const [aw, ah] = String(p.aspect_ratio).split(":").map(Number);
    if (Math.abs(info.display_width / info.display_height - aw / ah) / (aw / ah) > 0.02) checks.push(`frame ${info.display_width}x${info.display_height} is not ${p.aspect_ratio}`);
    if (clip?.dialogue && !info.has_audio) checks.push("planned dialogue but no audio track");
    updateRender(jobId, r.id, { contact_sheet: sheet, first_frame: first, status: "attached", probe: { ...info, technical_checks: checks } });
    attached.push({ id: r.id, clip_id: r.clip_id, checks });
  }
  const clips = plannedClips(job).map((c) => c.clip_id);
  const live = listRenders(jobId).filter((r) => r.status === "attached" || r.status === "selected");
  const covered = clips.every((c) => live.some((r) => r.clip_id === c));
  let state = getJob(jobId).state;
  if (covered && state === "RENDER_UPLOADED") {
    state = transition(jobId, "QC_PENDING", actor, `all ${clips.length} clip(s) have a take; quality review is open`, "RENDER_UPLOADED").state;
    await syncProductionStatus(jobId);
  }
  return { attached, state, waiting_for: clips.filter((c) => !live.some((r) => r.clip_id === c)) };
}

export interface ReviewInput {
  render_ids: number[];
  scores: Record<string, number | "na" | null>;
  defects: { check_id: string; start_seconds: number; end_seconds: number; note: string }[];
  comments: string;
  decision: "draft" | "approve" | "revision" | "reject";
  revision_stage?: "BRIEF_READY" | "SCRIPT_READY" | "STORYBOARD_READY" | "PROMPTS_READY" | "AWAITING_RENDER";
  reviewer: string;
  confirm_job_id: string;
}

/**
 * Record a human quality review. Scores are always a person's; nothing here scores a video.
 * approve → QC_APPROVED (real jobs also pass tools/approve.py's blockers and get production APPROVED);
 * revision → REVISION_REQUIRED (optionally reopening a stage); reject → back to AWAITING_RENDER;
 * draft → saved, no state change.
 */
export async function submitReview(jobId: string, input: ReviewInput, actor: Actor) {
  const job = getJob(jobId);
  if (actor.type !== "human") throw forbidden("quality reviews are recorded by people only");
  if (job.state !== "QC_PENDING") throw conflict(`reviews are recorded in QC_PENDING; the job is ${job.state}`);
  const renders = input.render_ids.map((id) => getRender(jobId, id));
  if (renders.some((r) => r.status !== "attached" && r.status !== "selected")) throw badRequest("review only attached takes");
  const clips = plannedClips(job).map((c) => c.clip_id);
  for (const c of clips) if (renders.filter((r) => r.clip_id === c).length !== 1) throw badRequest(`choose exactly one take for ${c}`);
  for (const d of input.defects) if (d.end_seconds < d.start_seconds) throw badRequest(`defect ${d.check_id}: end before start`);
  const known = new Set(applicable(job.performance_mode).map((c) => c.check_id));
  for (const k of Object.keys(input.scores)) if (!known.has(k) && input.scores[k] !== "na" && input.scores[k] !== null) throw badRequest(`${k} does not apply to ${job.performance_mode}`);

  const score = scoreReview(job.performance_mode, input.scores);
  if (score.invalid_na.length) throw badRequest(`these checks apply to this job and cannot be N/A: ${score.invalid_na.join(", ")}`);
  const decisive = input.decision !== "draft";
  if (decisive && (!input.reviewer.trim() || input.confirm_job_id.trim() !== jobId)) throw badRequest("enter your name and type the job id to confirm this decision");
  if (input.decision === "approve" && !score.passed) {
    throw new AppError(422, "qc_not_passed", `cannot approve: ${[...score.missing.map((m) => `${m} not scored`), ...score.failing.map((f) => `${f.check_id}=${f.score} (< ${f.min})`)].join(", ")}`, score);
  }
  const reviewer = input.reviewer.trim() || null;
  const named: Actor = { ...actor, name: reviewer ?? actor.name };

  // Write the scores into production.json (the Python approval rules read them there).
  const p = readJsonFile<Json>(repoPath(job.production_path));
  for (const q of p.quality_checks) {
    const s = input.scores[q.check_id];
    q.score = typeof s === "number" ? s : null;
    const notes = input.defects.filter((d) => d.check_id === q.check_id).map((d) => `${d.start_seconds}-${d.end_seconds}s: ${d.note}`);
    if (notes.length) q.notes = notes.join("; ");
  }

  if (input.decision === "approve") {
    await saveProduction(job, p);
    if (!job.is_test) {
      const { blockers } = await service<{ blockers: string[] }>(["approval-blockers", job.production_path]);
      if (blockers.length) throw new AppError(422, "approval_blocked", `cannot approve for delivery: ${blockers.join("; ")}`, { blockers });
    }
    transition(jobId, "QC_APPROVED", named, `QC approved by ${reviewer} (overall ${score.overall})${job.is_test ? " — TEST approval, not valid for commercial delivery" : ""}`, "QC_PENDING");
    if (!job.is_test) {
      p.status = "APPROVED";
      p.human_review = { required: true, reviewer, approved_on: new Date().toISOString().slice(0, 10), notes: input.comments || p.human_review.notes };
    } else {
      p.human_review.notes = `TEST approval by ${reviewer} on ${new Date().toISOString().slice(0, 10)}; never deliver commercially.`;
    }
    await saveProduction(getJob(jobId), p);
    for (const r of renders) updateRender(jobId, r.id, { status: "selected" });
    recordApproval(jobId, "qc", job.is_test ? "approved_test" : "approved", reviewer!, input.comments, null);
  } else {
    await saveProduction(job, p, { allowErrors: true });
    if (input.decision === "revision") {
      transition(jobId, "REVISION_REQUIRED", named, `revision requested by ${reviewer}: ${input.comments || "see review"}`, "QC_PENDING");
      recordApproval(jobId, "qc", "revision_requested", reviewer!, input.comments, null);
      if (input.revision_stage) transition(jobId, input.revision_stage, named, `revision: reopen ${input.revision_stage}`, "REVISION_REQUIRED");
    } else if (input.decision === "reject") {
      for (const r of renders) updateRender(jobId, r.id, { status: "rejected" });
      transition(jobId, "AWAITING_RENDER", named, `takes rejected by ${reviewer}: ${input.comments || "see review"}`, "QC_PENDING");
      recordApproval(jobId, "qc", "rejected", reviewer!, input.comments, null);
    }
    await syncProductionStatus(jobId);
  }
  if (input.decision === "revision" && input.revision_stage === "PROMPTS_READY") await writeRenderSheet(getJob(jobId));
  const review = insertReview({
    job_id: jobId, render_ids: input.render_ids, scores: input.scores, defects: input.defects, comments: input.comments,
    overall: score.overall, passed: score.passed, decision: input.decision, reviewer,
  });
  return { review, score, state: getJob(jobId).state };
}

/** Upload the first-frame still a Seedance clip starts from (or an optional Flow start frame). */
export async function uploadFirstFrame(jobId: string, clipId: string, body: ReadableStream<Uint8Array> | null, filename: string) {
  const job = getJob(jobId);
  if (!["PROMPTS_READY", "AWAITING_RENDER"].includes(job.state)) throw conflict("first frames are added after prompts are compiled, before rendering");
  if (!/^C\d{2,3}$/.test(clipId)) throw badRequest("bad clip id");
  const safe = safeFileName(filename, "image");
  const ext = path.extname(safe);
  const p = readJsonFile<Json>(repoPath(job.production_path));
  const list: Json[] = job.video_provider === "seedance" ? p.seedance_prompts : p.flow_prompts;
  const clip = list.find((c) => c.clip_id === clipId);
  if (!clip) throw badRequest(`clip ${clipId} is not planned`);
  const rel = `outputs/${jobId}/frames/${clipId}_first${ext}`;
  const abs = repoPath(rel);
  if (fs.existsSync(abs)) fs.rmSync(abs);
  await saveUpload(body, abs, "image");
  if (job.video_provider === "seedance") {
    // Seedance image-to-video starts from this still: point the clip at the uploaded file.
    const old: string | null = clip.first_frame;
    clip.first_frame = rel;
    if (old && old !== rel) p.reference_assets = p.reference_assets.filter((a: Json) => a.path !== old);
  } else if (clip.generation_mode === "frames_to_video") {
    clip.start_frame = rel;
  } else {
    clip.notes = `${clip.notes ?? ""} Optional start frame uploaded (${rel}); use it if you switch this clip to Frames to Video.`.trim();
  }
  if (!p.reference_assets.some((a: Json) => a.path === rel)) p.reference_assets.push({ path: rel, kind: "start_frame", character_id: null, rights_basis: job.is_test ? "internal_test_only" : "owned" });
  await saveProduction(job, p, { allowErrors: true });
  await writeRenderSheet(job);
  await syncProductionStatus(jobId);
  return { path: rel };
}
